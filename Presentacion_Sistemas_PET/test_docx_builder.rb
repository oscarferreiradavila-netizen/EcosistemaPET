require 'fileutils'

build_dir = "Presentacion_Sistemas_PET/docx_test_build"
FileUtils.rm_rf(build_dir)
FileUtils.mkdir_p("#{build_dir}/_rels")
FileUtils.mkdir_p("#{build_dir}/word/_rels")
FileUtils.mkdir_p("#{build_dir}/word/media")

File.write("#{build_dir}/[Content_Types].xml", <<~XML)
<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Default Extension="png" ContentType="image/png"/>
  <Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>
</Types>
XML

File.write("#{build_dir}/_rels/.rels", <<~XML)
<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>
</Relationships>
XML

File.write("#{build_dir}/word/_rels/document.xml.rels", <<~XML)
<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rIdImg1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/image" Target="media/image1.png"/>
</Relationships>
XML

FileUtils.cp("Presentacion_Sistemas_PET/screenshots/pet_peticion.png", "#{build_dir}/word/media/image1.png")

